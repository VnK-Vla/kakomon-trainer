def now_stamp() -> str:
    return datetime.now().strftime("%Y%m%d-%H%M%S")


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def backup_db(db_path: Path) -> Path | None:
    if not db_path.exists():
        return None
    backup_dir = APP_DIR / "backups" / f"before-diagnostic-reclassify-{now_stamp()}"
    backup_dir.mkdir(parents=True, exist_ok=True)
    target = backup_dir / db_path.name
    shutil.copy2(db_path, target)
    return target


def new_category(question_id: int, current: str) -> str:
    if question_id in OVERRIDES:
        return OVERRIDES[question_id]
    return BULK_RENAME.get(current, current)


def print_distribution(title: str, counts: Counter) -> None:
    print(title)
    for category in NEW_CATEGORIES:
        print(f"  {counts.get(category, 0):>4}  {category}")
    extras = sorted(set(counts) - set(NEW_CATEGORIES))
    for category in extras:
        print(f"  {counts.get(category, 0):>4}  [想定外] {category}")


def main() -> int:
    parser = argparse.ArgumentParser(description="Reclassify diagnostic radiology exam questions into the new 12 domains.")
    parser.add_argument("--db", type=Path, default=DEFAULT_DB)
    parser.add_argument("--dry-run", action="store_true", help="Show the before/after distribution without updating the database.")
    args = parser.parse_args()

    if not args.db.exists():
        print(f"error: database not found: {args.db}", file=sys.stderr)
        return 1

    with sqlite3.connect(args.db) as conn:
        rows = conn.execute(
            "SELECT id, category FROM questions WHERE exam = ?",
            (EXAM_NAME,),
        ).fetchall()

        before = Counter(category for _, category in rows)
        updates: list[tuple[str, str, int]] = []
        after = Counter()
        changed = 0
        for question_id, current in rows:
            category = new_category(question_id, current)
            after[category] += 1
            if category != current:
                changed += 1
            updates.append((category, now_iso(), question_id))

        print(f"対象: {len(rows)} 問（{EXAM_NAME}）")
        print_distribution("\n=== 変更前 ===", before)
        print_distribution("\n=== 変更後 ===", after)
        print(f"\n変更される設問数: {changed} / {len(rows)}")

        if args.dry_run:
            print("\n--dry-run のため DB は更新しません。")
            return 0

        backup = backup_db(args.db)
        if backup:
            print(f"\nbackup: {backup}")

        conn.executemany(
            "UPDATE questions SET category = ?, updated_at = ? WHERE id = ?",
            updates,
        )
        conn.commit()
        print(f"updated: {len(updates)} 問の分野を更新しました。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
